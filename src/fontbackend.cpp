namespace {
const char *kMarker = "generated by harbour-fontsettings";
const char *kDefaultFamily = "Sail Sans Pro Light";
const char *kFontSuffixes[] = {"ttf", "otf", "ttc", "TTF", "OTF", "TTC"};

QString dconfQuote(const QString &value)
{
    QString escaped = value;
    escaped.replace('\\', "\\\\");
    escaped.replace('\'', "\\'");
    return "'" + escaped + "'";
}
}

FontBackend::FontBackend(QObject *parent)
    : QObject(parent)
{
    loadState();
}

QString FontBackend::fontDir() const
{
    return QStandardPaths::writableLocation(QStandardPaths::GenericDataLocation) + "/fonts";
}

QString FontBackend::configDir() const
{
    return QStandardPaths::writableLocation(QStandardPaths::GenericConfigLocation) + "/fontconfig";
}

QString FontBackend::configPath() const
{
    return configDir() + "/fonts.conf";
}

QString FontBackend::statePath() const
{
    return QStandardPaths::writableLocation(QStandardPaths::GenericConfigLocation)
            + "/harbour-fontsettings/state.conf";
}

QString FontBackend::defaultFamily() const
{
    return QLatin1String(kDefaultFamily);
}

bool FontBackend::isConfigured() const
{
    return configIsOurs();
}

QStringList FontBackend::families()
{
    if (m_families.isEmpty())
        refresh();
    return m_families;
}

QStringList FontBackend::installedFamiliesFromFc() const
{
    QStringList result;
    QProcess p;
    p.start("fc-list", QStringList() << ":" << "family");
    if (!p.waitForFinished(5000))
        return result;
    const QString out = QString::fromLocal8Bit(p.readAllStandardOutput());
    for (const QString &line : out.split('\n')) {
        for (const QString &name : line.split(',')) {
            const QString trimmed = name.trimmed();
            if (!trimmed.isEmpty() && !result.contains(trimmed))
                result << trimmed;
        }
    }
    result.sort(Qt::CaseInsensitive);
    return result;
}

QString FontBackend::familyOfFile(const QString &path) const
{
    QProcess p;
    p.start("fc-scan", QStringList() << "--format" << "%{family}\n" << path);
    if (!p.waitForFinished(5000))
        return QString();
    const QString out = QString::fromLocal8Bit(p.readAllStandardOutput()).trimmed();
    if (out.isEmpty())
        return QString();
    return out.split('\n').first().split(',').first().trimmed();
}

void FontBackend::refresh()
{
    m_families = QFontDatabase().families();
    m_imported.clear();

    QDir dir(fontDir());
    const QStringList filters = {"*.ttf", "*.otf", "*.ttc", "*.TTF", "*.OTF", "*.TTC"};
    const QFileInfoList files = dir.entryInfoList(filters, QDir::Files, QDir::Name);
    for (const QFileInfo &fi : files) {
        QString family = familyOfFile(fi.absoluteFilePath());
        if (family.isEmpty()) {
            const int id = QFontDatabase::addApplicationFont(fi.absoluteFilePath());
            if (id >= 0 && !QFontDatabase::applicationFontFamilies(id).isEmpty())
                family = QFontDatabase::applicationFontFamilies(id).first();
        }
        QVariantMap entry;
        entry.insert("family", family.isEmpty() ? fi.completeBaseName() : family);
        entry.insert("file", fi.fileName());
        entry.insert("path", fi.absoluteFilePath());
        m_imported << entry;
    }

    // Imported families may only appear after fontconfig has rescanned; make
    // sure they are still selectable right after an import.
    for (const QVariant &v : m_imported) {
        const QString family = v.toMap().value("family").toString();
        if (!family.isEmpty() && !m_families.contains(family))
            m_families << family;
    }
    m_families.sort(Qt::CaseInsensitive);
    emit familiesChanged();
}

void FontBackend::setPrimary(const QString &family)
{
    if (m_primary == family)
        return;
    m_primary = family;
    saveState();
    emit selectionChanged();
}

void FontBackend::setHeading(const QString &family)
{
    if (m_heading == family)
        return;
    m_heading = family;
    saveState();
    emit selectionChanged();
}

void FontBackend::setMono(const QString &family)
{
    if (m_mono == family)
        return;
    m_mono = family;
    saveState();
    emit selectionChanged();
}

void FontBackend::addFallback(const QString &family)
{
    if (family.isEmpty() || m_fallbacks.contains(family))
        return;
    m_fallbacks << family;
    saveState();
    emit fallbacksChanged();
}

void FontBackend::removeFallback(const QString &family)
{
    if (m_fallbacks.removeAll(family) > 0) {
        saveState();
        emit fallbacksChanged();
    }
}

void FontBackend::moveFallback(int from, int to)
{
    if (from < 0 || from >= m_fallbacks.size() || to < 0 || to >= m_fallbacks.size() || from == to)
        return;
    m_fallbacks.move(from, to);
    saveState();
    emit fallbacksChanged();
}

bool FontBackend::importFont(const QString &path)
{
    const QFileInfo fi(path);
    if (!fi.exists() || !fi.isFile()) {
        setMessage(QStringLiteral("文件不存在：%1").arg(path));
        return false;
    }

    bool suffixOk = false;
    for (const char *suffix : kFontSuffixes) {
        if (fi.suffix() == QLatin1String(suffix)) {
            suffixOk = true;
            break;
        }
    }
    if (!suffixOk) {
        setMessage(QStringLiteral("只支持 .ttf / .otf / .ttc 字体文件"));
        return false;
    }

    QDir().mkpath(fontDir());
    const QString dst = fontDir() + "/" + fi.fileName();

    if (QFileInfo(dst).exists()) {
        if (QFileInfo(dst).canonicalFilePath() == fi.canonicalFilePath()) {
            setMessage(QStringLiteral("这个字体已经在字体目录里了"));
            return true;
        }
        if (!QFile::remove(dst)) {
            setMessage(QStringLiteral("无法覆盖已有文件：%1").arg(dst));
            return false;
        }
    }

    if (!QFile::copy(fi.absoluteFilePath(), dst)) {
        setMessage(QStringLiteral("复制失败：%1").arg(dst));
        return false;
    }

    runFcCache();
    refresh();
    setMessage(QStringLiteral("已导入 %1").arg(fi.fileName()));
    return true;
}

bool FontBackend::removeImported(const QString &path)
{
    const QFileInfo fi(path);
    const QString dir = QDir(fontDir()).canonicalPath();
    const QString canonical = fi.canonicalFilePath();
    if (!canonical.startsWith(dir + "/")) {
        setMessage(QStringLiteral("只能删除导入的字体"));
        return false;
    }
    if (!QFile::remove(fi.absoluteFilePath())) {
        setMessage(QStringLiteral("删除失败：%1").arg(fi.fileName()));
        return false;
    }
    runFcCache();
    refresh();
    setMessage(QStringLiteral("已删除 %1").arg(fi.fileName()));
    return true;
}

QString FontBackend::buildConfig() const
{
    const QString primary = m_primary.isEmpty() ? defaultFamily() : m_primary;

    QStringList preferred;
    preferred << primary;
    for (const QString &f : m_fallbacks) {
        if (f != primary && !preferred.contains(f))
            preferred << f;
    }
    preferred << QStringLiteral("emoji");

    QString xml;
    QTextStream s(&xml);
    s << "<?xml version=\"1.0\"?>\n"
         "<!DOCTYPE fontconfig SYSTEM \"fonts.dtd\">\n"
         "<!-- " << kMarker << " — 由「字体设置」生成，修改会被覆盖 -->\n"
         "<fontconfig>\n";

    auto writeAlias = [&s](const QString &target, const QStringList &families) {
        s << "  <alias binding=\"strong\">\n"
             "    <family>" << target.toHtmlEscaped() << "</family>\n"
             "    <prefer>\n";
        for (const QString &f : families) {
            if (!f.trimmed().isEmpty())
                s << "      <family>" << f.toHtmlEscaped() << "</family>\n";
        }
        s << "    </prefer>\n"
             "  </alias>\n";
    };

    writeAlias(QStringLiteral("Sail Sans Pro Light"), preferred);

    QStringList headingPreferred;
    headingPreferred << (m_heading.isEmpty() ? primary : m_heading);
    for (const QString &f : preferred) {
        if (!headingPreferred.contains(f))
            headingPreferred << f;
    }
    writeAlias(QStringLiteral("Sail Sans Pro ExtraLight"), headingPreferred);

    if (!m_mono.isEmpty()) {
        writeAlias(QStringLiteral("monospace"),
                   QStringList() << m_mono << QStringLiteral("emoji"));
        writeAlias(QStringLiteral("DejaVu Sans Mono"), QStringList() << m_mono);
    }

    if (primary != defaultFamily()) {
        s << "  <selectfont>\n"
             "    <rejectfont>\n"
             "      <glob>/usr/share/fonts/sail-sans-pro</glob>\n"
             "    </rejectfont>\n"
             "  </selectfont>\n";
    }

    s << "</fontconfig>\n";
    return xml;
}

bool FontBackend::configIsOurs() const
{
    QFile f(configPath());
    if (!f.open(QIODevice::ReadOnly))
        return false;
    return f.readAll().contains(kMarker);
}

void FontBackend::runFcCache()
{
    QProcess p;
    p.start("fc-cache", QStringList() << "-f");
    p.waitForFinished(20000);
}

bool FontBackend::dconfWrite(const QString &key, const QString &value)
{
    QProcess p;
    p.start("dconf", QStringList() << "write"
            << "/desktop/sailfish/silica/" + key << dconfQuote(value));
    return p.waitForFinished(5000) && p.exitCode() == 0;
}

bool FontBackend::dconfReset(const QString &key)
{
    QProcess p;
    p.start("dconf", QStringList() << "reset" << "/desktop/sailfish/silica/" + key);
    return p.waitForFinished(5000) && p.exitCode() == 0;
}

bool FontBackend::apply()
{
    QDir().mkpath(configDir());

    if (QFile::exists(configPath()) && !configIsOurs()) {
        const QString backup = configPath() + ".before-harbour-fontsettings";
        if (!QFile::exists(backup))
            QFile::copy(configPath(), backup);
    }

    QFile f(configPath());
    if (!f.open(QIODevice::WriteOnly | QIODevice::Truncate)) {
        setMessage(QStringLiteral("无法写入 %1").arg(configPath()));
        return false;
    }
    f.write(buildConfig().toUtf8());
    f.close();

    runFcCache();

    // These are optional: inside the sailjail sandbox dconf may be unavailable,
    // in which case the fontconfig alias above still does the work.
    if (m_primary.isEmpty() || m_primary == defaultFamily())
        dconfReset(QStringLiteral("font_family"));
    else
        dconfWrite(QStringLiteral("font_family"), m_primary);

    if (!m_heading.isEmpty())
        dconfWrite(QStringLiteral("font_family_heading"), m_heading);
    else
        dconfReset(QStringLiteral("font_family_heading"));

    saveState();
    emit selectionChanged();
    setMessage(QStringLiteral("已保存，重启主屏幕后生效"));
    return true;
}

bool FontBackend::reset()
{
    bool ok = true;
    if (configIsOurs()) {
        const QString backup = configPath() + ".before-harbour-fontsettings";
        if (QFile::exists(backup)) {
            QFile::remove(configPath());
            ok = QFile::copy(backup, configPath());
            QFile::remove(backup);
        } else {
            ok = QFile::remove(configPath());
        }
    }

    dconfReset(QStringLiteral("font_family"));
    dconfReset(QStringLiteral("font_family_heading"));
    dconfReset(QStringLiteral("font_family_mono"));

    m_primary.clear();
    m_heading.clear();
    m_mono.clear();
    m_fallbacks.clear();
    saveState();
    runFcCache();
    emit selectionChanged();
    emit fallbacksChanged();
    setMessage(ok ? QStringLiteral("已恢复系统默认字体") : QStringLiteral("恢复默认时出错"));
    return ok;
}

bool FontBackend::restartHomeScreen()
{
    QProcess p;
    p.start("systemctl", QStringList() << "--user" << "restart" << "lipstick");
    if (!p.waitForFinished(15000))
        return false;
    return p.exitStatus() == QProcess::NormalExit && p.exitCode() == 0;
}

void FontBackend::loadState()
{
    QSettings s(statePath(), QSettings::IniFormat);
    m_primary = s.value("font/primary").toString();
    m_heading = s.value("font/heading").toString();
    m_mono = s.value("font/mono").toString();
    m_fallbacks = s.value("font/fallbacks").toStringList();

    if (m_primary.isEmpty() && m_fallbacks.isEmpty() && !s.contains("font/initialised")) {
        // First start: keep the system font, but pre-fill the CJK/emoji
        // families this device ships so the fallback chain is not empty.
        const QStringList available = installedFamiliesFromFc();
        for (const QString &candidate : {QStringLiteral("WenQuanYi Zen Hei"),
                                         QStringLiteral("Noto Color Emoji"),
                                         QStringLiteral("Noto Emoji"),
                                         QStringLiteral("DejaVu Sans")}) {
            if (available.contains(candidate))
                m_fallbacks << candidate;
        }
        s.setValue("font/initialised", true);
    }
}

void FontBackend::saveState()
{
    QDir().mkpath(QFileInfo(statePath()).absolutePath());
    QSettings s(statePath(), QSettings::IniFormat);
    s.setValue("font/primary", m_primary);
    s.setValue("font/heading", m_heading);
    s.setValue("font/mono", m_mono);
    s.setValue("font/fallbacks", m_fallbacks);
    s.setValue("font/initialised", true);
    s.sync();
}

void FontBackend::setMessage(const QString &msg)
{
    m_message = msg;
    emit messageChanged();
}

int FontBackend::runCli(const QStringList &args)
{
    QTextStream out(stdout);
    QTextStream err(stderr);

    const QString cmd = args.isEmpty() ? QStringLiteral("status") : args.first();
    QStringList rest = args.mid(1);

    if (cmd == QLatin1String("status")) {
        out << "primary=" << (m_primary.isEmpty() ? defaultFamily() : m_primary) << "\n";
        out << "heading=" << (m_heading.isEmpty() ? QStringLiteral("-") : m_heading) << "\n";
        out << "mono=" << (m_mono.isEmpty() ? QStringLiteral("-") : m_mono) << "\n";
        out << "fallbacks=" << m_fallbacks.join(",") << "\n";
        out << "config=" << (configIsOurs() ? "managed"
                                            : (QFile::exists(configPath()) ? "foreign" : "none")) << "\n";
        out << "config_path=" << configPath() << "\n";
        return 0;
    }

    if (cmd == QLatin1String("list")) {
        for (const QString &f : installedFamiliesFromFc())
            out << f << "\n";
        return 0;
    }

    if (cmd == QLatin1String("import")) {
        if (rest.isEmpty()) {
            err << "usage: --cli import <font-file>\n";
            return 2;
        }
        const bool ok = importFont(rest.first());
        out << lastMessage() << "\n";
        return ok ? 0 : 1;
    }

    if (cmd == QLatin1String("apply")) {
        for (int i = 0; i < rest.size(); ++i) {
            const QString opt = rest.at(i);
            const QString val = (i + 1 < rest.size()) ? rest.at(i + 1) : QString();
            if (opt == QLatin1String("--primary")) { m_primary = val; ++i; }
            else if (opt == QLatin1String("--heading")) { m_heading = val; ++i; }
            else if (opt == QLatin1String("--mono")) { m_mono = val; ++i; }
            else if (opt == QLatin1String("--fallback")) { m_fallbacks << val; ++i; }
            else { err << "unknown option: " << opt << "\n"; return 2; }
        }
        const bool ok = apply();
        out << lastMessage() << "\n";
        return ok ? 0 : 1;
    }

    if (cmd == QLatin1String("reset")) {
        const bool ok = reset();
        out << lastMessage() << "\n";
        return ok ? 0 : 1;
    }

    err << "commands: status | list | import <file> | apply [--primary F] [--heading F] "
           "[--mono F] [--fallback F]... | reset\n";
    return 2;
}
